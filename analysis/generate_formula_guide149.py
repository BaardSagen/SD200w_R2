"""Build concise customer help; internal analysis stays outside the guide."""
from pathlib import Path
import json
R=Path(__file__).resolve().parent.parent
topics=[]
for part in (R/'docs/SIT_CONVERSIONS_AND_FORMULAS.md').read_text(encoding='utf-8').split('\n## ')[1:]:
    title,body=part.split('\n',1)
    topics.append((title,body.strip()))
topics.append(('GSW licence',(R/'sit_import/vendor/gsw/LICENSE').read_text(encoding='utf-8')))
out=['// Generated by analysis/generate_formula_guide149.py; edit the Markdown source.']
for title,body in topics:
    assert len(body)<20000
    out.append(' {L'+json.dumps(title,ensure_ascii=True)+',')
    out.append('\n'.join('  L'+json.dumps(line.replace('\n','\r\n'),ensure_ascii=True) for line in body.splitlines(keepends=True))+'},')
(R/'sit_import/formula_guide.inc').write_text('\n'.join(out)+'\n',encoding='ascii')
(R/'analysis/formula_guide149_topics.json').write_text(json.dumps([dict(title=t,text=b.replace('\n','\r\n')) for t,b in topics],indent=2),encoding='utf-8')
print('Generated',len(topics),'customer topics plus 9 operating topics.')
