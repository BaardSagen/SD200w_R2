"""Generate offline formula pages and a complete copyable reference appendix."""
from pathlib import Path
import ast,json,hashlib
R=Path(__file__).resolve().parent.parent
source=R/'docs/SIT_CONVERSIONS_AND_FORMULAS.md'
parts=source.read_text(encoding='utf-8').split('\n## ')[1:]
topics=[]
for part in parts:
 title,body=part.split('\n',1)
 topics.append((title,body.strip()))
code=(R/'analysis/recovered_formulas.py').read_text(encoding='utf-8-sig')
tree=ast.parse(code);lines=code.splitlines(keepends=True)
groups=[('Reference: salinity',['salinity']),('Reference: sound speed',['sound_velocity']),('Reference: density',['density0','density_anomaly','legacy_sigma']),('Reference: depth / oxygen',['gravity','depth_unesco','oxygen_saturation_mg_l'])]
appendix=[]
for title,names in groups:
 block='import math\n\n'+ '\n\n'.join(''.join(lines[n.lineno-1:n.end_lineno]).rstrip() for n in tree.body if isinstance(n,ast.FunctionDef) and n.name in names)
 topics.append((title,block));appendix.append('## '+title+'\n\n```python\n'+block+'\n```\n')
extra='''# Illustrative wrappers around the recovered core, not the complete SIT UI.
def temperature_from_resistance(R, a, b, c, d, old_kelvin=False):
    r = math.log(R)
    return 1/(a+b*r+c*r*r+d*r*r*r)-(273.16 if old_kelvin else 273.15)

def logger_depth(S, T, P, latitude=45.508368287):
    rho = 1000+density_anomaly(S,T,P)
    return 10000*P/(rho*gravity(latitude,P))

def oxygen_units(S, T, P, AP_hPa, percent):
    mg = oxygen_saturation_mg_l(S,T,AP_hPa*760/1013.25)*percent/100
    rho = 1000+density_anomaly(S,T,P)
    return (mg, mg*22.391/31.998, mg*1000/31.998,
            mg*22.391*1000/(716.467218*(rho/1000)))

# Two positive, increasing-pressure endpoints: illustration only.
def illustrative_layers(points, latitude=45.508368287):
    z = 0.0
    previous = 0.0
    for S,T,P in points:
        rho = 1000+density_anomaly(S,T,P)
        z += 10000*(P-previous)/(rho*gravity(latitude,P))
        previous = P
    return z

print(salinity(33.719632,7.773,16.72)) # 32.53899947
print(logger_depth(32.539,7.773,16.72)) # 16.62646309 m
print(sound_velocity(32.539,7.773,16.72)) # 1488.82737409 m/s
print(oxygen_units(32.539,7.773,16.72,925,3.47))
# mg/L, mL/L, umol/L, umol/kg (specified EOS-80 density convention)
print(illustrative_layers([(23.738,14.461,.30),(32.539,7.773,16.72)]))
# 16.62881923 m; not a whole-file Profiling result
'''
topics.append(('Reference: worked examples',extra));appendix.append('## Reference: worked examples\n\n```python\n'+extra+'\n```\n')
(R/'docs/SIT_FORMULA_REFERENCE.md').write_text('# SIT copyable equation reference\n\nGenerated with the offline guide. Concatenate the Python blocks in order. See SIT_CONVERSIONS_AND_FORMULAS.md for units, scope and limitations.\n\n'+'\n'.join(appendix),encoding='utf-8')
(R/'analysis/formula_guide148_reference.py').write_text('\n\n'.join(t for name,t in topics if name.startswith('Reference:')),encoding='utf-8')
science=(R/'sit_import/science.h').read_text()
start=science.index('inline double mackenzie')
end=science.rfind('\n}\n#endif')
topics.append(('Reference: acoustic alternatives', 'Complete C++ functions used by Convert. S=SP; temperature and pressure/depth conventions appear in each function.\n\n'+science[start:end]))
topics.append(('GSW licence', (R/'sit_import/vendor/gsw/LICENSE').read_text(encoding='utf-8')))
out=['// Generated by analysis/generate_formula_guide148.py; edit the Markdown source.']
for title,body in topics:
 assert len(body)<30000
 out.append(' {L'+json.dumps(title,ensure_ascii=True)+',')
 chunks=body.replace('\r\n','\n').splitlines(keepends=True)
 out.append('\n'.join('  L'+json.dumps(line.replace('\n','\r\n'),ensure_ascii=True) for line in chunks)+'},')
(R/'sit_import/formula_guide.inc').write_text('\n'.join(out)+'\n',encoding='ascii')
(R/'analysis/formula_guide148_topics.json').write_text(json.dumps([dict(title=a,text=b.replace('\n','\r\n')) for a,b in topics],indent=2),encoding='utf-8')
print('Generated',len(topics),'formula topics')
